import React, { createContext, useContext, useEffect, useState } from 'react'

/* ── Language context ─────────────────────────────────────────── */
const Ctx = createContext({ lang: 'ka', setLang: () => {} })

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('nvic-lang') || 'ka')
  useEffect(() => {
    localStorage.setItem('nvic-lang', lang)
    document.documentElement.lang = lang
    document.title = lang === 'ka'
      ? 'NVIC — კონკურსის დაწყების საორგანიზაციო სივრცე | New Vision Innovation Challenge'
      : 'NVIC Launch Hub — New Vision Innovation Challenge'
  }, [lang])
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>
}

export function useLang() { return useContext(Ctx) }

/** t(ka, en, vars) — Georgian first (default language), English second. */
export function useT() {
  const { lang } = useContext(Ctx)
  return (ka, en, vars) => {
    let s = lang === 'ka' ? ka : en
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v)
    return s
  }
}

