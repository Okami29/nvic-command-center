// Reverse lookup: original English text → Georgian (for activity-log targets)
const REV = {}
for (const [id, v] of Object.entries(TASK_KA)) REV['task:' + id] = v
for (const v of Object.values(TASK_KA)) REV['t:' + v] = v
for (const [id, v] of Object.entries(DOC_KA)) { REV['doc:' + id] = v.name; REV['d:' + v.name] = v.name }
for (const [id, v] of Object.entries(EVENT_KA)) { REV['event:' + id] = v.title; REV['e:' + v.title] = v.title }
for (const [id, v] of Object.entries(RESP_KA)) { REV['resp:' + id] = v.func; REV['r:' + v.func] = v.func }
for (const [id, v] of Object.entries(Q_KA)) { REV['q:' + id] = v.q; REV['qq:' + v.q] = v.q }
for (const [id, v] of Object.entries(NOTE_KA)) REV['n:' + v] = v.slice(0, 40)
export const kaTarget = (table, id, text) => {
  if (getLang() !== 'ka') return text
  return REV[`${{ tasks: 'task', documents: 'doc', events: 'event', responsibilities: 'resp', questions: 'q', notes: 'n', workstreams: 'ws' }[table] || 'x'}:${id}`]
    || REV[`t:${text}`] || REV[`d:${text}`] || REV[`e:${text}`] || REV[`r:${text}`] || REV[`qq:${text}`] || REV[`n:${text}`]
    || (text && text.length > 40 ? text.slice(0, 40) + '…' : text) || `#${id}`
}
